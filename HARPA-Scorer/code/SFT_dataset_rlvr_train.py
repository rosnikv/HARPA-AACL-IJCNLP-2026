# -------- Prompt Template -------- #
TEMPLATE = [
    {"role": "system", "content": SYSTEM_PROMPT},
    {"role": "user", "content": ""}
]


# -------- Build a Single Formatted Prompt -------- #

def build_context_messages(prompt, response_a, response_b):
    template = copy.deepcopy(TEMPLATE) 

    # Format the system prompt with execution metadata
    template[1]["content"] = (
        f"[Client Prompt]\n{prompt}\n\n"
        f"[The Start of Proposal A]\n{response_a}\n[The End of Proposal A]\n\n"
        f"[The Start of Proposal B]\n{response_b}\n[The End of Proposal B]\n\n"
    )
    return template

def convert_from_hf(input_path, output_dir):
    ds = load_from_disk(input_path)

    context_messages = []
    winners = []
    ground_truth_strings = []
    labels_list = []

    for item in ds:
        prompt = item["prompt"]
        response_a = item["response_a"]
        response_b = item["response_b"]

        context = build_context_messages(prompt, response_a, response_b)
        context_messages.append(context)
        winners.append(item["ground_truth"])         # already "response_a"/"response_b"
        ground_truth_strings.append(item["ground_truth"])
        labels_list.append(item.get("labels"))

    dataset = Dataset.from_dict({
        "context_messages": context_messages,
        "winner": winners,
        "ground_truth": ground_truth_strings,
        "labels": labels_list
    })

    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    dataset.save_to_disk(str(output_path))
    print(f"✅ Dataset saved to {output_dir} with {len(dataset)} examples")

# -------- Run Example -------- #
